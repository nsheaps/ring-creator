import type { Control, HeadModel, Params } from '../types';

// ---------- shared controls ----------
const prongCount = (min: number, max: number): Control => ({ type: 'number', key: 'prongCount', label: 'Prongs', min, max, step: 1, help: 'Number of prongs holding the centre stone. Corners of pointed cuts are covered first.' });
const prongStyle: Control = {
  type: 'select',
  key: 'prongStyle',
  label: 'Prong tips',
  options: [
    { value: 'round', label: 'Round bead' },
    { value: 'claw', label: 'Pointed claw' },
    { value: 'tab', label: 'Flat tab' },
    { value: 'v', label: 'V (chevron)' },
  ],
  help: 'Shape of the prong tip that folds over the stone.',
};
const prongWidth: Control = { type: 'number', key: 'prongWidth', label: 'Prong wire', min: 0.5, max: 1.6, step: 0.05, unit: 'mm', help: 'Wire diameter. Thicker prongs are stronger but cover more of the stone.' };
const galleryRails: Control = { type: 'number', key: 'galleryRails', label: 'Gallery rails', min: 0, max: 3, step: 1, help: 'Horizontal wires that tie the prongs together under the stone.' };
const baseScale: Control = { type: 'number', key: 'baseScale', label: 'Base footprint', min: 0, max: 0.9, step: 0.05, help: 'Size of the seat as a fraction of the stone outline. 0 = automatic.' };
const prongControls = (min: number, max: number): Control[] => [prongCount(min, max), prongStyle, prongWidth, galleryRails, baseScale];
const prongDefaults = (count: number, style: string, rails: number): Params => ({ prongCount: count, prongStyle: style, prongWidth: 0.9, galleryRails: rails, baseScale: 0 });

const haloShape: Control = {
  type: 'select',
  key: 'haloShape',
  label: 'Halo shape',
  options: [
    { value: 'follow', label: 'Follow the stone' },
    { value: 'round', label: 'Round' },
    { value: 'cushion', label: 'Cushion' },
    { value: 'oval', label: 'Oval' },
  ],
};
const haloControls: Control[] = [
  haloShape,
  { type: 'number', key: 'haloGap', label: 'Halo gap', min: 0, max: 1.5, step: 0.05, unit: 'mm', help: 'Space between the centre stone and the halo.' },
  { type: 'number', key: 'meleeSize', label: 'Melee size', min: 0, max: 3, step: 0.1, unit: 'mm', help: '0 = use the accent stone size.' },
  { type: 'number', key: 'meleeSpacing', label: 'Melee spacing', min: 0, max: 0.8, step: 0.02, unit: 'mm' },
  { type: 'number', key: 'haloDrop', label: 'Halo drop', min: 0, max: 1.5, step: 0.05, unit: 'mm', help: 'How far the halo sits below the centre girdle.' },
  prongStyle,
  prongWidth,
];
const haloDefaults = (shape: string): Params => ({ haloShape: shape, haloGap: 0.25, meleeSize: 0, meleeSpacing: 0.12, haloDrop: 0.3, prongStyle: 'round', prongWidth: 0.8 });

