import type { BandStyleModel, Control, Params } from '../types';

/**
 * Wedding band styles. `builder` = key registered by src/geometry/bands (equal to the style id).
 * Width and thickness come from the design (BandSpec.widthMm / thicknessMm); params tune the style.
 * Men's styles carry `minWidthMm` / `minThicknessMm`, which raise the band to a men's size unless set to 0.
 */

// ---------- shared controls ----------
const profile = (exclude: string[] = []): Control => ({
  type: 'select',
  key: 'profile',
  label: 'Profile',
  options: [
    { value: 'comfort-dome', label: 'Comfort dome' },
    { value: 'flat', label: 'Flat' },
    { value: 'beveled', label: 'Bevelled edges' },
    { value: 'half-round', label: 'Half round (D)' },
    { value: 'knife', label: 'Knife edge' },
  ].filter((o) => !exclude.includes(o.value)),
  help: 'Cross-section of the band seen end-on.',
});
const comfortFit: Control = {
  type: 'toggle',
  key: 'comfortFit',
  label: 'Comfort fit',
  help: 'Rounds the inside of the band so it slides over the knuckle easily.',
};
const coverage: Control = {
  type: 'select',
  key: 'coverage',
  label: 'Stones around',
  options: [
    { value: 'half', label: 'Half way (top)' },
    { value: 'three-quarter', label: 'Three quarters' },
    { value: 'full', label: 'All the way' },
  ],
  help: 'How far around the band the stones run. Full eternity bands cannot be resized.',
};
const setting: Control = {
  type: 'select',
  key: 'setting',
  label: 'Stone setting',
  options: [
    { value: 'shared-prong', label: 'Shared prong' },
    { value: 'channel', label: 'Channel' },
    { value: 'bezel', label: 'Bezel' },
  ],
};
const stoneSize: Control = {
  type: 'number',
  key: 'stoneSize',
  label: 'Stone size',
  min: 0,
  max: 4,
  step: 0.1,
  unit: 'mm',
  help: '0 = use the accent stone size. Always limited to what fits the band width.',
};
const gapMm = (def: { min: number; max: number }): Control => ({
  type: 'number',
  key: 'gapMm',
  label: 'Gap between stones',
  min: def.min,
  max: def.max,
  step: 0.01,
  unit: 'mm',
});
const scallop: Control = {
  type: 'toggle',
  key: 'scallop',
  label: 'Scalloped sides',
  help: 'Cuts a U-shaped arch into the side of the band under every stone, so light reaches the stones from the side.',
};
const twoTone: Control = {
  type: 'toggle',
  key: 'twoTone',
  label: 'Two-tone',
  help: 'Uses the second metal for part of the band.',
};
const minWidth: Control = {
  type: 'number',
  key: 'minWidthMm',
  label: 'Minimum width',
  min: 0,
  max: 10,
  step: 0.5,
  unit: 'mm',
  help: "Men's styles default to a wider band. 0 = use the band width exactly.",
};
const minThickness: Control = {
  type: 'number',
  key: 'minThicknessMm',
  label: 'Minimum thickness',
  min: 0,
  max: 3,
  step: 0.1,
  unit: 'mm',
  help: '0 = use the band thickness exactly.',
};

const surface: Control = {
  type: 'select',
  key: 'surface',
  label: 'Surface',
  options: [
    { value: 'smooth', label: 'Smooth' },
    { value: 'brushed', label: 'Brushed grain' },
    { value: 'engraved', label: 'Engraved scroll' },
  ],
  help: 'Brushed cuts fine grain lines round the band; engraved cuts a running scroll over the top half.',
};

